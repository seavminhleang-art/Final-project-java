    public static String[] getBannerForTitle(String title) {
        if (title == null) return null;
        String upper = title.toUpperCase();
        if (upper.equals("PROCTOR")) return ASCII_PROCTOR;
        if (upper.equals("LOG IN") || upper.equals("LOGIN") || upper.equals("SIGN IN")) return ASCII_LOGIN;
        if (upper.equals("REGISTER") || upper.contains("SIGN UP") || upper.contains("CREATE ACCOUNT")) return ASCII_REGISTER;
        if (upper.contains("DASHBOARD") || upper.contains("PORTAL")) return ASCII_DASHBOARD;
        if (upper.contains("SECURITY") || upper.contains("PASSWORD")) return ASCII_SECURITY;
        if (upper.contains("HISTORY")) return ASCII_HISTORY;
        if (upper.contains("SPEED")) return ASCII_SPEED;
        if (upper.contains("EXAM")) return ASCII_EXAMS;
        if (upper.contains("QUIZ")) return ASCII_QUIZZES;
        if (upper.contains("INBOX") || upper.contains("NOTIFICATION") || upper.contains("MESSAGE")) return ASCII_INBOX;
        if (upper.contains("USER")) return ASCII_USERS;
        if (upper.contains("REPORT")) return ASCII_REPORTS;
        if (upper.contains("LEADERBOARD")) return ASCII_LEADERBOARD;
        if (upper.contains("SUBMISSION") || upper.contains("ANSWER SHEET") || upper.contains("ATTEMPT")) return ASCII_SUBMISSIONS;
        if (upper.contains("QUESTION")) return ASCII_QUESTIONS;
        if (upper.contains("SUBJECT") || upper.contains("TEACHER ASSIGNMENT")) return ASCII_SUBJECTS;
        if (upper.contains("QUIT") || upper.contains("GOODBYE") || upper.contains("EXIT")) return ASCII_GOODBYE;
        return null;
    }
